// GET /corporations/{id} omits faction_id for every NPC corporation except
// the four faction-warfare militia corps, so the station owner's faction --
// required for the broker-fee standings term (docs/spec/v2.md §9) -- must
// come from the SDE. Vendoring the mapping keeps the fee path free of any
// runtime SDE dependency.
package npcfactions

